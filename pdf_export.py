"""
Server-side PDF export for analysis results.

Renders ONLY the analysis markdown (explanation, DDI/DLTI sections, sources,
coverage limitations, disclaimer) into a text-based PDF. UI controls (buttons,
language dropdowns, chatbot) are never part of the input, so they cannot leak
into the export. No clinical logic lives here; text is rendered verbatim.
"""

import io
import re
from datetime import date
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    HRFlowable, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
)

MAX_MARKDOWN_CHARS = 200_000

EXPORT_TITLE = "Medical Report Analyzer \u2013 Informational Research Prototype Output"
EXPORT_SUBTITLES = {
    "medicine": "Prescription analysis",
    "report": "Laboratory report analysis",
    "symptoms": "Symptom information",
}
FILENAME_PREFIXES = {
    "medicine": "Prescription_Analysis",
    "report": "Lab_Report_Analysis",
    "symptoms": "Symptom_Analysis",
}
EXPORT_DISCLAIMER = (
    "This document is generated by an informational research prototype. It is "
    "not a medical device, does not diagnose any condition, and does not "
    "instruct any change to medication. Consult a qualified healthcare "
    "professional before making any medical decision."
)

# Helvetica (standard PDF font) supports Latin-1 only; map common symbols and
# drop emoji/unsupported glyphs rather than emitting black boxes.
_CHAR_MAP = {
    "\u2013": "-", "\u2014": "-", "\u2018": "'", "\u2019": "'",
    "\u201c": '"', "\u201d": '"', "\u2022": "-", "\u2192": "->",
    "\u2265": ">=", "\u2264": "<=", "\u00a0": " ", "\u2026": "...",
    "\u26a0": "[!]", "\u2139": "[i]", "\u2713": "[ok]",
}


def pdf_filename(kind: str = "medicine", today: date = None) -> str:
    prefix = FILENAME_PREFIXES.get(kind, FILENAME_PREFIXES["medicine"])
    return f"{prefix}_{(today or date.today()).isoformat()}.pdf"


def _sanitize(text: str) -> str:
    out = []
    for ch in text:
        if ch in _CHAR_MAP:
            out.append(_CHAR_MAP[ch])
        elif ord(ch) < 256 and (ch >= " " or ch in "\n\t"):
            out.append(ch)
        # else: emoji / non-Latin-1 glyph dropped
    return "".join(out)


def _inline(text: str) -> str:
    """Convert a markdown inline fragment to reportlab paragraph markup."""
    text = escape(_sanitize(text))
    text = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r"\1 (\2)", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<![\*\w])\*(?!\s)(.+?)(?<!\s)\*(?![\*\w])", r"<i>\1</i>", text)
    text = re.sub(r"(?<![\w])_(?!\s)([^_\n]+?)(?<!\s)_(?![\w])", r"<i>\1</i>", text)
    text = re.sub(r"`([^`]+)`", r'<font face="Courier">\1</font>', text)
    return text.strip()


def _styles():
    base = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=base["BodyText"], fontName="Helvetica",
                          fontSize=9.5, leading=13, alignment=TA_LEFT, spaceAfter=3)
    return {
        "title": ParagraphStyle("title", parent=base["Title"], fontName="Helvetica-Bold",
                                fontSize=15, leading=19, spaceAfter=2, alignment=TA_LEFT),
        "subtitle": ParagraphStyle("subtitle", parent=body, textColor=colors.HexColor("#4b5563"),
                                   spaceAfter=6),
        "body": body,
        "bullet": ParagraphStyle("bullet", parent=body, leftIndent=12, bulletIndent=2),
        "quote": ParagraphStyle("quote", parent=body, leftIndent=8, borderPadding=4,
                                backColor=colors.HexColor("#fffbeb"),
                                borderColor=colors.HexColor("#f59e0b"), borderWidth=0.6,
                                spaceBefore=3, spaceAfter=5),
        "cell": ParagraphStyle("cell", parent=body, fontSize=8.5, leading=11, spaceAfter=0),
        # keepWithNext keeps every heading attached to the content that follows.
        1: ParagraphStyle("h1", parent=body, fontName="Helvetica-Bold", fontSize=14, leading=18,
                          spaceBefore=8, spaceAfter=4, keepWithNext=1),
        2: ParagraphStyle("h2", parent=body, fontName="Helvetica-Bold", fontSize=12.5, leading=16,
                          spaceBefore=10, spaceAfter=4, keepWithNext=1,
                          textColor=colors.HexColor("#1e3a8a")),
        3: ParagraphStyle("h3", parent=body, fontName="Helvetica-Bold", fontSize=11, leading=14,
                          spaceBefore=8, spaceAfter=3, keepWithNext=1),
        4: ParagraphStyle("h4", parent=body, fontName="Helvetica-Bold", fontSize=10, leading=13,
                          spaceBefore=6, spaceAfter=2, keepWithNext=1),
    }


def _split_row(line: str):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _is_separator(line: str) -> bool:
    return bool(re.match(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$", line))


def _table(rows, styles, width):
    ncols = max(len(r) for r in rows)
    data = []
    for i, r in enumerate(rows):
        r = r + [""] * (ncols - len(r))
        cells = []
        for c in r:
            txt = _inline(c)
            if i == 0:
                txt = f"<b>{txt}</b>"
            cells.append(Paragraph(txt, styles["cell"]))
        data.append(cells)
    if ncols == 2:
        col_widths = [width * 0.38, width * 0.62]
    else:
        col_widths = [width / ncols] * ncols
    t = Table(data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#9ca3af")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e5e7eb")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]))
    return t


def markdown_to_flowables(markdown: str, width: float):
    styles = _styles()
    story, lines, i = [], markdown.replace("\r\n", "\n").split("\n"), 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if not stripped:
            i += 1
            continue
        # Strip HTML disclosure wrapper tags from PDF output while preserving enclosed content
        if re.match(r"^</?details>$", stripped, re.IGNORECASE):
            i += 1
            continue
        summary_m = re.match(r"^<summary>(.*?)</summary>$", stripped, re.IGNORECASE)
        if summary_m:
            summary_content = summary_m.group(1).strip()
            # Begin Technical Details and Evidence on a new PDF page after patient summary
            if re.search(r"technical\s+.*details", summary_content, re.IGNORECASE):
                while story and isinstance(story[-1], (HRFlowable, Spacer)):
                    story.pop()
                if story:
                    story.append(PageBreak())
            story.append(Paragraph(_inline(summary_content), styles[2]))
            i += 1
            continue
        if re.match(r"^-{3,}$|^\*{3,}$", stripped):
            story.append(HRFlowable(width="100%", thickness=0.6, color=colors.HexColor("#d1d5db"),
                                    spaceBefore=4, spaceAfter=4))
            i += 1
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if m:
            level = min(len(m.group(1)), 4)
            heading_content = m.group(2)
            # Begin Technical Details and Evidence on a new PDF page after patient summary
            if re.search(r"technical\s+.*details", heading_content, re.IGNORECASE):
                while story and isinstance(story[-1], (HRFlowable, Spacer)):
                    story.pop()
                if story:
                    story.append(PageBreak())
            story.append(Paragraph(_inline(heading_content), styles[level]))
            i += 1
            continue
        if stripped.startswith("|"):
            block = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                if not _is_separator(lines[i]):
                    block.append(_split_row(lines[i]))
                i += 1
            if block:
                story.append(_table(block, styles, width))
                story.append(Spacer(1, 4))
            continue
        if stripped.startswith(">"):
            quote = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                quote.append(lines[i].strip().lstrip(">").strip())
                i += 1
            story.append(Paragraph(_inline(" ".join(q for q in quote if q)), styles["quote"]))
            continue
        b = re.match(r"^(\s*)([-*+]|\d+\.)\s+(.*)$", line)
        if b:
            indent = min(len(b.group(1)) // 2, 3) * 10
            marker = "-" if b.group(2) in "-*+" else b.group(2)
            st = ParagraphStyle("b", parent=styles["bullet"], leftIndent=12 + indent,
                                bulletIndent=2 + indent)
            story.append(Paragraph(_inline(b.group(3)), st, bulletText=marker))
            i += 1
            continue
        para = [stripped]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(
                r"^(#{1,6}\s|\||>|-{3,}$|\s*([-*+]|\d+\.)\s)", lines[i].strip()):
            para.append(lines[i].strip())
            i += 1
        story.append(Paragraph(_inline(" ".join(para)), styles["body"]))
    return story


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(colors.HexColor("#6b7280"))
    canvas.drawString(doc.leftMargin, 10 * mm,
                      "Informational research prototype - not medical advice")
    canvas.drawRightString(A4[0] - doc.rightMargin, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def build_analysis_pdf(markdown: str, kind: str = "medicine", today: date = None) -> bytes:
    """Return PDF bytes for the given analysis markdown. Raises ValueError on bad input."""
    if not isinstance(markdown, str) or not markdown.strip():
        raise ValueError("No analysis content available to export.")
    if len(markdown) > MAX_MARKDOWN_CHARS:
        raise ValueError("Analysis content is too large to export.")

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
        topMargin=16 * mm, bottomMargin=18 * mm,
        title=EXPORT_TITLE, author="Medical Report Analyzer (research prototype)",
    )
    width = A4[0] - doc.leftMargin - doc.rightMargin
    styles = _styles()
    subtitle = EXPORT_SUBTITLES.get(kind, EXPORT_SUBTITLES["medicine"])
    stamp = (today or date.today()).isoformat()

    story = [
        Paragraph(_inline(EXPORT_TITLE), styles["title"]),
        Paragraph(_inline(f"{subtitle} - generated {stamp}"), styles["subtitle"]),
        HRFlowable(width="100%", thickness=1, color=colors.HexColor("#2563eb"), spaceAfter=6),
    ]
    story.extend(markdown_to_flowables(markdown, width))
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=0.6, color=colors.HexColor("#d1d5db"),
                            spaceAfter=4))
    story.append(Paragraph(_inline("**Disclaimer:** " + EXPORT_DISCLAIMER), styles["quote"]))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
